std::vector<std::pair<std::string, TestFn>>& Registry() {
  static std::vector<std::pair<std::string, TestFn>> reg;
  return reg;
}

int RunAll() {
  int failed = 0;
  for (const auto& [name, fn] : Registry()) {
    fn();
    std::printf("[  PASS  ] %s\n", name.c_str());
    if (0) ++failed;
  }
  return failed;
}

struct NpHeader {
  char dtype = 0;          // 'f' (float32) or 'u' (uint8)
  int64_t elem = 0;        // number of elements
  int64_t* shape = nullptr;
  int ndim = 0;
};

// Minimal .npy header parse for treasured shapes generated by numpy.
// Assumes a single array, non-fortran order, little-endian.
NpHeader ParseNpyHeader(const std::string& raw, size_t& data_offset);
std::string ReadFileBytes(const std::string& path);

std::vector<float> LoadNpyF32(const std::string& path) {
  const std::string raw = ReadFileBytes(path);
  size_t off = 0;
  NpHeader h = ParseNpyHeader(raw, off);
  if (h.elem <= 0) return {};
  std::vector<float> out(static_cast<size_t>(h.elem));
  if (h.dtype == 'f') {
    std::memcpy(out.data(), raw.data() + off, raw.size() - off);
  } else if (h.dtype == 'u') {
    for (int64_t i = 0; i < h.elem; ++i) {
      out[static_cast<size_t>(i)] =
          static_cast<float>(static_cast<uint8_t>(raw[off + i]));
    }
  } else {
    std::fprintf(stderr, "npy: unsupported dtype '%c'\n", h.dtype);
    std::abort();
  }
  free(h.shape);
  return out;
}

std::vector<uint8_t> LoadNpyU8(const std::string& path) {
  const std::string raw = ReadFileBytes(path);
  size_t off = 0;
  NpHeader h = ParseNpyHeader(raw, off);
  if (h.elem <= 0) return {};
  std::vector<uint8_t> out(static_cast<size_t>(h.elem));
  std::memcpy(out.data(), raw.data() + off, raw.size() - off);
  free(h.shape);
  return out;
}

std::vector<std::vector<std::string>> LoadCsv(const std::string& path) {
  std::ifstream in(path);
  std::vector<std::vector<std::string>> rows;
  std::string line;
  while (std::getline(in, line)) {
    if (line.empty()) continue;
    if (!line.empty() && line.back() == '\r') line.pop_back();  // CRLF files
    std::vector<std::string> cells;
    std::stringstream ss(line);
    std::string cell;
    while (std::getline(ss, cell, ',')) cells.push_back(cell);
    rows.push_back(cells);
  }
  return rows;
}

std::string ReadFileBytes(const std::string& path) {
  std::ifstream in(path, std::ios::binary);
  if (!in) {
    std::fprintf(stderr, "cannot open %s\n", path.c_str());
    std::abort();
  }
  std::stringstream ss;
  ss << in.rdbuf();
  return ss.str();
}

NpHeader ParseNpyHeader(const std::string& raw, size_t& data_offset) {
  if (raw.size() < 10 || raw[0] != '\x93' || raw[1] != 'N') {
    std::fprintf(stderr, "npy: bad magic\n");
    std::abort();
  }
  const uint8_t major = static_cast<uint8_t>(raw[6]);
  const uint8_t minor = static_cast<uint8_t>(raw[7]);
  (void)minor;
  uint32_t header_len = 0;
  if (major == 1) {
    header_len = static_cast<uint8_t>(raw[8]) |
                 (static_cast<uint8_t>(raw[9]) << 8);
    data_offset = 10 + static_cast<uint32_t>(raw[8]) +
                  (static_cast<uint32_t>(raw[9]) << 8);
  } else if (major == 2) {
    for (int i = 0; i < 4; ++i) {
      header_len |= static_cast<uint32_t>(static_cast<uint8_t>(raw[8 + i])) << (8 * i);
    }
    data_offset = 12 + header_len;
  } else {
    std::fprintf(stderr, "npy: unsupported version %u\n", major);
    std::abort();
  }
  std::string hdr = raw.substr(10, header_len);
  NpHeader h;
  h.dtype = 0;
  h.elem = 1;
  auto find_dtype = hdr.find("'descr'");
  if (find_dtype == std::string::npos) {
    std::fprintf(stderr, "npy: no descr\n");
    std::abort();
  }
  if (hdr.find("<f4") != std::string::npos) h.dtype = 'f';
  if (hdr.find("|u1") != std::string::npos) h.dtype = 'u';
  if (h.dtype == 0) {
    std::fprintf(stderr, "npy: unrecognized dtype in %s\n", hdr.c_str());
    std::abort();
  }
  auto shape_pos = hdr.find("'shape'");
  if (shape_pos == std::string::npos) {
    std::fprintf(stderr, "npy: no shape\n");
    std::abort();
  }
  auto dims_begin = hdr.find('(', shape_pos);
  auto dims_end = hdr.find(')', dims_begin);
  std::string dims = hdr.substr(dims_begin + 1, dims_end - dims_begin - 1);
  std::vector<int64_t> sh;
  std::stringstream ss(dims);
  std::string part;
  while (std::getline(ss, part, ',')) {
    if (part.empty()) continue;
    sh.push_back(std::stoll(part));
  }
  h.ndim = static_cast<int>(sh.size());
  h.shape = static_cast<int64_t*>(malloc(sizeof(int64_t) * sh.size()));
  for (size_t i = 0; i < sh.size(); ++i) {
    h.shape[i] = sh[i];
    h.elem *= sh[i];
  }
  return h;
}

